#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Validate that AGENTS.md stays a pointer document.

AGENTS.md is the always-loaded entry point, so long prose belongs in a skill or a
reference file that AGENTS.md points at. Any prose block over the word threshold must
carry a pointer into `.ai/` (a skill, reference, pattern or agent) that carries the
detail.
"""

import re
import sys
from pathlib import Path
from typing import List

# Set UTF-8 encoding for Windows console
if sys.platform == 'win32':
    import io
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
    sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding='utf-8')

# Determine template root (script location is .ai/tests/)
SCRIPT_DIR = Path(__file__).parent
TEMPLATE_ROOT = SCRIPT_DIR.parent.parent
AGENTS_MD = TEMPLATE_ROOT / "AGENTS.md"

WORD_THRESHOLD = 100
POINTER_RE = re.compile(r"\.ai/(skills|reference|patterns|agents)/")

# The installed skills/agents index is generated by `.ai/scripts/catalog.py`
# from item frontmatter between these markers, and every sync rewrites it.
# It is machine-owned, so it is skipped rather than treated as prose the
# document could point away from.
GENERATED_RE = re.compile(
    r"<!-- (?:ai-workspace-manager|ai-manager):installed:start -->.*?"
    r"<!-- (?:ai-workspace-manager|ai-manager):installed:end -->",
    re.S,
)


def _split_blocks(text: str) -> List[List[str]]:
    """Split into blocks on blank lines, tracking fenced code blocks so their
    contents are never treated as prose."""
    blocks: List[List[str]] = []
    current: List[str] = []
    in_fence = False

    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            # A fence line is structural; keep the code block out of prose blocks
            # entirely by flushing any pending prose and starting fresh.
            if current:
                blocks.append(current)
                current = []
            continue
        if in_fence:
            # Inside a fenced code block: not prose, do not accumulate.
            continue
        if stripped == "":
            if current:
                blocks.append(current)
                current = []
            continue
        current.append(line)

    if current:
        blocks.append(current)
    return blocks


def _is_structural(block: List[str]) -> bool:
    """A block that is only table rows and/or headings carries no prose to point away."""
    content = [ln.strip() for ln in block if ln.strip()]
    if not content:
        return True
    for ln in content:
        if ln.startswith("|"):
            continue
        if ln.startswith("#"):
            continue
        return False
    return True


def _word_count(block: List[str]) -> int:
    return sum(len(ln.split()) for ln in block)


def main() -> int:
    print("=========================================")
    print("  AGENTS.md Prose Pointer Validation")
    print("=========================================")
    print()

    if not AGENTS_MD.exists():
        print(f"❌ AGENTS.md not found: {AGENTS_MD}")
        print()
        print("0 block(s) over 100 words, 1 without a .ai/ pointer")
        return 1

    text = AGENTS_MD.read_text(encoding='utf-8')
    text = GENERATED_RE.sub("", text)
    blocks = _split_blocks(text)

    over_threshold = 0
    without_pointer = 0

    for block in blocks:
        if _is_structural(block):
            continue
        words = _word_count(block)
        if words <= WORD_THRESHOLD:
            continue
        over_threshold += 1
        joined = "\n".join(block)
        if not POINTER_RE.search(joined):
            without_pointer += 1
            first_line = next((ln.strip() for ln in block if ln.strip()), "")
            print(f"❌ {AGENTS_MD.name}: block starting \"{first_line}\" "
                  f"({words} words) has no .ai/ pointer")

    print()
    print("=========================================")
    print(f"{over_threshold} block(s) over {WORD_THRESHOLD} words, "
          f"{without_pointer} without a .ai/ pointer")
    print("=========================================")

    if without_pointer:
        print("❌ SOME PROSE BLOCKS LACK A POINTER")
        return 1
    print("✅ ALL OVER-THRESHOLD BLOCKS POINT AT .ai/")
    return 0


if __name__ == '__main__':
    sys.exit(main())
